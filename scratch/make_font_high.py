C = 3
def offs(w):
    return [] if w == 0 else [0] if w == 1 else [-1, 1]

def box(u, d, l, r):
    px = [['.'] * 8 for _ in range(8)]
    # A generic arm: 'axis' lines along the arm, perpendicular arms p1 (negative side) and p2.
    def arm(w, sign, p1, p2, opp, vertical):
        perp = [C + o for o in offs(p1)] + [C + o for o in offs(p2)]
        for o in offs(w):
            pos = C + o
            if o == 0:
                if opp:
                    stop = 7 if sign < 0 else 0
                elif p1 or p2:
                    near = min(perp) if sign < 0 else max(perp)
                    far = max(perp) if sign < 0 else min(perp)
                    stop = near if (p1 and p2) or opp else far
                elif opp:
                    stop = 7 if sign < 0 else 0
                else:
                    stop = C
            else:
                side, other = (p1, p2) if o < 0 else (p2, p1)
                if side:
                    lines = [C + q for q in offs(side)]
                    stop = min(lines) if sign < 0 else max(lines)
                elif opp:
                    stop = 7 if sign < 0 else 0
                elif other:
                    lines = [C + q for q in offs(other)]
                    stop = max(lines) if sign < 0 else min(lines)
                else:
                    stop = C
            start = 0 if sign < 0 else 7
            for t in range(min(start, stop), max(start, stop) + 1):
                if vertical:
                    px[t][pos] = '#'
                else:
                    px[pos][t] = '#'
    arm(u, -1, l, r, d, True)
    arm(d, +1, l, r, u, True)
    arm(l, -1, u, d, r, False)
    arm(r, +1, u, d, l, False)
    return [''.join(row) for row in px]

for code, arms in BOX.items():
    put(code, box(*arms))

