"""One-off generator for Dine's original 8x8 glyphs 80h-FFh (code page 437
layout). Accented letters reuse the project's own 00h-7Fh glyphs; box and
block characters are computed; the rest are drawn here. Appends to
src/dos_font8x8.txt after review."""
L = [l for l in open('src/dos_font8x8.txt').read().splitlines() if not l.startswith(';')]
low = {int(L[i * 9][:2], 16): L[i * 9 + 1:i * 9 + 9] for i in range(128)}

def g(ch):
    return list(low[ord(ch)])

ACC = {
    'uml': ['.##..##.'[1:] + '.', '........'],
    'acute': ['...##...', '..##....'],
    'grave': ['.##.....', '..##....'],
    'circ': ['..##....', '.#..#...'],
    'tilde': ['.##.#...', '#.##....'],
}
ACC['uml'] = ['##..##..', '........']

def accented(ch, acc, shift=0):
    rows = g(ch)
    a = [r[-shift:] + r[:-shift] if shift else r for r in ACC[acc]]
    return a + rows[2:]

def lower_i(acc):
    # dotless i body with an accent
    rows = g('i')
    a = ACC[acc]
    if acc == 'uml':
        a = ['.##.##..', '........']
    elif acc == 'circ':
        a = ['..##....', '.#..#...']
    return a + rows[2:]

H = {}
def put(code, rows):
    rows = rows if isinstance(rows, list) else rows.split()
    assert len(rows) == 8 and all(len(r) == 8 and set(r) <= set('.#') for r in rows), (hex(code), rows)
    H[code] = rows

